import type {
  InvestorDocumentInput,
  InvestorDocumentResult,
} from '@cap-event/contracts';
import { Injectable } from '@nestjs/common';

import { buildSimplePdf } from './pdf.util';
import { badRequest } from '../common/utils/rpc-error.util';

const money = (value?: number): string =>
  (value ?? 0).toLocaleString('en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });

/** Placeholder investor notice: a one-page PDF summarising the input. Not a real template. */
@Injectable()
export class DocumentsService {
  generate({
    capEvent,
    lineItem,
  }: InvestorDocumentInput): InvestorDocumentResult {
    const entries = lineItem?.plInvestorEntries ?? [];
    if (entries.length === 0) {
      throw badRequest('lineItem must contain the investor entries');
    }
    const investors = new Set(entries.map((e) => e.customerId));
    if (investors.size > 1) {
      throw badRequest('lineItem must contain entries of a single investor');
    }
    const entry = entries.find((e) => e.isAggregated) ?? entries[0];

    const lines = [
      '(PLACEHOLDER - generated by a stand-in service, not a real notice)',
      '',
      `Capital event: ${capEvent.name ?? capEvent.capEventType?.name ?? '-'}`,
      `Type: ${capEvent.capEventType?.name ?? '-'}`,
      `Sponsor: ${capEvent.sponsor?.name ?? capEvent.sponsor?.id ?? '-'}`,
      `Fund group: ${capEvent.fundGroup?.name ?? capEvent.fundGroup?.id ?? '-'}`,
      `Entity: ${lineItem.entity?.id ?? '-'} ${lineItem.entity?.name ?? ''}`.trim(),
      `Notice date: ${capEvent.noticeDate ?? '-'}   Due date: ${lineItem.dueDate ?? '-'}`,
      '',
      `Investor: ${entry.investor ?? '-'} (${entry.customerId ?? '-'})`,
      `Commitment: ${money(entry.commitment)}`,
      `Invested capital: ${money(entry.investedCapital)}`,
      `Unfunded: ${money(entry.unfunded)}`,
      `Amount due: ${money(entry.allocatedAmount)}`,
    ];

    const pdf = buildSimplePdf('Investor Notice', lines);
    return {
      contentBase64: pdf.toString('base64'),
      contentType: 'application/octet-stream',
    };
  }
}
